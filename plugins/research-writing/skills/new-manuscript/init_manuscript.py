# -*- coding: utf-8 -*-
r"""Creates a new manuscript project — tools, settings and the tracker file skeleton in one go.

Usage:  (`<py>` is this computer's Python 3 — `python` on Windows, `python3` on macOS)
    <py> -X utf8 init_manuscript.py <target folder> --name "Paper title" [options]

Options:
    --kind journal|dissertation      default journal
    --source-dir manuscript_src      folder of the manuscript .md files (default: the settings default)
    --chapters intro.md results.md   chapter files; without it, ch1..chN from --chapter-count
    --chapter-count 4
    --references bib.md
    --build-script build.py          without it, the build-reference check is skipped
    --triggers "now,when working on the section,..."   (the `now` trigger is always added)
    --force                          overwrite existing files too (default: skip them)

Existing files are **skipped**, so running it twice is safe.
Folder and file names follow DEFAULTS in `tools/_config.py` and are written as they are into the new `.manuscript/project.json`.
"""

import argparse
import io
import json
import os
import shutil
import sys

def _utf8_console():
    """The default Windows console (cp949) cannot print characters such as '—' and dies mid-output.
    Switch standard output to UTF-8 so the script runs from any shell,
    without having to set `PYTHONIOENCODING` first."""
    for _s in (sys.stdout, sys.stderr):
        try:
            _s.reconfigure(encoding='utf-8', errors='replace')
        except (AttributeError, ValueError, OSError):
            pass


_utf8_console()

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, 'tools'))
from _config import DEFAULTS, TRIGGER_NOW, is_now, tok  # noqa: E402  — the one place for default names and format tokens

# names written into the templates — the same values as the generated settings
N = dict(DEFAULTS['tracker'], tools=DEFAULTS['tools_dir'])
# managed_files.json is the single source of the files copied into and managed in projects —
# the updater (update_tools.py) and the hash builder (scripts/tool_hashes.py) read the same file.
MANAGED = json.load(io.open(os.path.join(HERE, 'managed_files.json'), encoding='utf-8'))['files']
HOOKS_SRC = os.path.join(HERE, 'hooks')
# .claude/settings.json — the PreToolUse hook that stops the Write tool from overwriting E*.md records and the generated index.
# Same content as hooks/settings.example.json. If settings.json already exists, it is skipped with a note.
SETTINGS_JSON = io.open(os.path.join(HOOKS_SRC, 'settings.example.json'), encoding='utf-8').read() \
    if os.path.isfile(os.path.join(HOOKS_SRC, 'settings.example.json')) else ''

DEFAULT_TRIGGERS = list(DEFAULTS['tracker']['triggers'])


def w(path, text, force, made, skipped):
    if os.path.exists(path) and not force:
        skipped.append(path)
        return
    d = os.path.dirname(path)
    if d and not os.path.isdir(d):
        os.makedirs(d)
    io.open(path, 'w', encoding='utf-8', newline='').write(text)
    made.append(path)


def tracker_index(name, triggers):
    tl = ' · '.join('`%s`' % t for t in triggers)
    return """# Tracker index — {name}

The handover index between sessions. **At the start of every session, read only this file, in full.**
Open-item bodies are in `{pending}`; completion records are in `{record_index}`.

**§2–§6 are generated by `{tools}/tidy_tracker.py`. Do not edit them by hand.**

## 1. Writing rules

- Register a new item at the bottom of a category table in `{pending}` with `<py> -X utf8 {tools}/new_pending.py <row file>` — write the
  row's ID cell as `<letter>?` (e.g. `D?`) and the tool assigns the number (plugin `tracker-workflow.md` "Concurrent editing"). Do not pick a number by hand.
- `Location` names the file and the section — the path relative to the root in backticks, the section right after it. The location table is built from it
  (syntax: plugin `tracker-workflow.md` "Target and location syntax").
- `Trigger` takes exactly one of the values below. Any other value makes the tidy tool warn.

  {tl}

- `Status` starts with a status word such as `waiting` · `in progress` · `on hold` · `applied` · `done` · `closed` (the tools read the head of the cell).
  A status that still contains `waiting` or `needed`, such as `done (visual check needed)`, is open.
  `applied` is before the user's confirmation, so it stays in the list.

## 2. Standing — environment constraints

<!-- standing-F -->
| ID | Item | Status | Note |
|---|---|---|---|
<!-- /standing-F -->

## 3. Location table — when you touch this section, open these items

<!-- location-table -->

<!-- /location-table -->

## 4. Trigger table — when this condition clears, take up these items

<!-- trigger-table -->

<!-- /trigger-table -->

## 5. Items that can be done now

<!-- now -->

<!-- /now -->

## 6. Chapter in progress

<!-- focus -->

<!-- /focus -->
""".format(name=name, tl=tl, **N)


def tracker_pending():
    head = """# Open items — bodies

Finding an item takes two steps. **Do not read this file end to end — get the ID from the index and read only that item.**

    1) the location table of {index}:   <file> <section>  ->  D3 · H1
    2) read only that row in this file

## Rules of this file

- One item is one table row. If it needs a long explanation, add `### <ID> details` below the table.
- **IDs are never reused.** `{tools}/new_pending.py` assigns the number of a new item; completed items move to `{archive}`.
- When the status becomes `done` or `closed`, the tidy tool archives the item.
""".format(**N)
    titles = {
        'A': 'A. Awaiting confirmation — items that can be touched only after an outside condition is settled',
        'B': 'B. To change together when a later chapter or section is settled',
        'C': 'C. Format to check',
        'D': 'D. Style and consistency — for the final cross-check',
    }
    body = []
    for cls in ['A', 'B', 'C', 'D']:
        body.append("""
## {t}

| ID | Item | Location | Trigger | Status | Note |
|---|---|---|---|---|---|

<!-- archived-list:{c} -->
<!-- /archived-list:{c} -->
""".format(t=titles[cls], c=cls))
    return head + ''.join(body)


