RECORDS_README = """# Completion records — format

**One file per item.** The file name is `E<number>.md`.

    # E<number> — title

    **Completed** YYYY-MM-DD
    **Target** the files and sections changed
    **Status** applied (awaiting confirmation) | confirmed | closed

    ## Background
    ...

- `Target` becomes the reverse index of the record index — write each changed file as **the full path relative to the root, in backticks**, and put the
  section (`③` · `¶2` · `§3.2.1` · `Figure 3`) **right after** that path. For a range without a file, use one word such as `all`.
  Syntax: plugin `tracker-workflow.md` "Target and location syntax".
- When `Status` may say `confirmed`: plugin `revision-protocol.md` "Approval and comparison".
- **A confirmed item is not edited — a new number replaces it.**
- **Make a new item with `<py> {tools}/new_record.py <body file>`.** Write the first line of the body as `# E? — title` and
  the tool takes the next free number atomically and fills in `E?`. Do not count numbers by hand and create the file with Write —
  the hook in `.claude/settings.json` refuses a Write to an existing `E*.md`.
- After adding or changing items, rebuild the index with `<py> {tools}/index_records.py`.
- `<py>` above is this computer's Python 3 — `python` on Windows, `python3` on macOS.
""".format(**N)

