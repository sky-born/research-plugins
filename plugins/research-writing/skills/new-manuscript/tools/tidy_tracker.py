# ---------------------------------------------------------------- utilities
def norm(s):
    """Comparison string with Markdown emphasis and whitespace removed"""
    return re.sub(r'\s+', '', re.sub(r'\*\*|`', '', unicodedata.normalize('NFC', s)))


def strip_md(s):
    return re.sub(r'\s+', ' ', re.sub(r'\*\*|`', '', s)).strip()


# numkey(i) — ID sort key. Alias of _config.id_key (same definition as sync S3 · S7).
# cells(line) — '| a | b \| c |' -> ['a', 'b \| c']. Alias of _config.split_cells (`\|` inside a cell is not a boundary).


def is_closed(status):
    """With this status value the item moves from the list to the completion records. The vocabulary is in `_config.py` (shared with the index tool)."""
    return state_is_closed(status)


RC_REFUSED = 4      # save refused — lock not taken, or a file changed after reading. Run again


class StaleFile(Exception):
    """A file someone else changed after it was read. Keeps edits made directly in another window from being overwritten."""


class Doc:
    def __init__(self, path):
        self.path = path
        self.orig = open(path, encoding='utf-8').read()
        self.lines = self.orig.split('\n')
        self.mtime = os.path.getmtime(path)

    def dirty(self):
        return '\n'.join(self.lines) != self.orig

    def stale(self):
        """True if the file changed after it was read. Compares the content too, so an mtime-only change is filtered out."""
        if os.path.getmtime(self.path) == self.mtime:
            return False
        return open(self.path, encoding='utf-8').read() != self.orig

    def save(self):
        if self.stale():
            raise StaleFile(self.path)
        open(self.path, 'w', encoding='utf-8', newline='').write('\n'.join(self.lines).rstrip() + '\n')

    def block(self, key, letter=''):
        """(start, end) indexes of the block `BLOCKS[key]` — <!-- name --> ... <!-- /name --> in either spelling (English first).
        The end is the closing line itself. `letter` fills a per-class marker (`archived-list:A`)."""
        for spelling in BLOCKS[key]:
            name = spelling.format(letter)
            try:
                a = self.lines.index(f'<!-- {name} -->')
                b = self.lines.index(f'<!-- /{name} -->')
            except ValueError:
                continue
            return a, b
        return None

    def set_block(self, key, body, letter=''):
        """Replaces the inside of the block with body (list) — the markers stay as found. True if it changed"""
        bl = self.block(key, letter)
        if bl is None:
            return None
        a, b = bl
        if self.lines[a + 1:b] == body:
            return False
        self.lines[a + 1:b] = body
        return True

    def sections(self):
        """List of (heading, start, end) per '## X. ...' heading"""
        out, cur = [], None
        for i, l in enumerate(self.lines):
            if l.startswith('## '):
                if cur:
                    out.append(cur + (i,))
                cur = (l, i)
        if cur:
            out.append(cur + (len(self.lines),))
        return out


def table_rows(lines, a, b):
    """(index, ID, cells, column names) within the range"""
    hdr = None
    out = []
    for i in range(a, b):
        l = lines[i]
        if HDR.match(l):
            hdr = cells(l)
        m = ROW.match(l)
        if m and hdr:
            out.append((i, m.group(1), cells(l), hdr))
    return out


def entries(lines, a, b):
    """(index, ID, title, completion date) of items in sub-heading form

    Reads `### E47 — title` together with the `**Completed** 2026-08-05` that follows it (either spelling of the label).
    Only the first separator is used, so a title containing more `—` stays intact.
    """
    out = []
    for i in range(a, b):
        m = HEAD.match(lines[i])
        if not m:
            continue
        date = ''
        for j in range(i + 1, min(i + 6, b)):
            if HEAD.match(lines[j]):
                break
            d = DATE.match(lines[j])
            if d:
                date = d.group(1).strip()
                break
        out.append((i, m.group(1), m.group(2).strip(), date))
    return out


def cls_of(rid):
    return re.match(r'^[A-Z]+', rid).group(0)


# Location keys follow the `_location.py` syntax — record index §1, the §3 location table here and the focus share the definition.
_GRAMMAR = None


def grammar():
    global _GRAMMAR
    if _GRAMMAR is None:
        _GRAMMAR = Grammar(_CFG)
    return _GRAMMAR


def loc_rows(cell):
    """Location cell → [(path relative to the root, section, is a file), ...]. Text without a file → (text, '', False); an empty cell → `('(no location)', '', False)`.

    No exclusion is applied — the location of an open item is the actual place to edit, so items that name tracker files keep them.
    The second return value is the parse result (used to decide warnings).
    """
    p = grammar().parse(cell)
    out = []
    if p.files:
        for path, secs in p.files.items():
            for s in (secs or ['']):
                out.append((path, s, True))
    elif p.free_text:
        out.append((p.free_text, '', False))
    else:
        out.append((tok(PLACEHOLDERS['no_location']), '', False))
    return out, p


def loc_bad(p):
    """A fixable location parse failure — an empty cell, or section or identifier markers with no file to attach them to."""
    return p.empty or (not p.files and bool(p.orphans))


def loc_sort(row):
    path, sec = row[0], row[1]
    return grammar().sort_key(path, sec)


def col(hdr, key, default=None):
    """Index of the column whose name is `COLUMNS[key]` in either spelling — tables are joined by key, not by the written name,
    so an English pending table and a Korean archive (or the reverse) still line up."""
    for j, h in enumerate(hdr):
        if column_key(h) == key:
            return j
    return default


# Column names differ per table — pending (item · note), proposals (proposal · basis).
def col_any(hdr, keys, fallback=None):
    for k in keys:
        j = col(hdr, k)
        if j is not None:
            return j
    return fallback


def source_col(hdr, name):
    """Index in `hdr` of the column that `name` (a header cell of another table) means — `ID` as is, known names by key,
    unknown names by the same written name."""
    if norm(name) == 'ID':
        return next((j for j, h in enumerate(hdr) if norm(h) == 'ID'), None)
    k = column_key(name)
    if k:
        return col(hdr, k)
    return next((j for j, h in enumerate(hdr) if norm(h) == norm(name)), None)


# ---------------------------------------------------------------- main
class Tidy:
    def __init__(self, d, apply_, focus=None, sync=None):
        self.apply = apply_
        self.focus = focus          # 'ch3' / 'off' / None (leave as is)
        self.d = d
        self.hot = Doc(os.path.join(d, _CFG.index_file))
        self.pend = Doc(os.path.join(d, _CFG.pending_file))
        self.rec = Doc(os.path.join(d, REC))
        self.lit = Doc(os.path.join(d, _CFG.literature_file))
        self.pro = Doc(os.path.join(d, _CFG.proposals_file))
        self.notes, self.warns, self.acts = [], [], []
        self._open_state = None     # (open rows, reasons to skip) — _rows_or_gaps sets it once per run
        self.stale = []             # files caught by the pre-save check — changed by someone else after reading
        self.sync = sync or Sync(_CFG)
        for f in FILES + [REC]:                    # local snapshot of the pre-write version — for the later difference and for restores (not made again for the same hash)
            self.sync.before_write(f.replace('\\', '/'))

    def warn(self, s):
        self.warns.append(s)

    def act(self, s):
        self.acts.append(s)

    # --- 1) completed and closed items: list → completion records §4 ---
    def migrate(self):
        blk = self.rec.block('archive_body')
        if blk is None:
            self.warn('The archive has no `<!-- %s -->` block. Archiving skipped.' % tok(BLOCKS['archive_body']))
            return
        a, b = blk
        dest_hdr = cells(self.rec.lines[a + 1])
        # separator under the header — restores the line that the first archive run of older versions deleted along with the rows (without it Markdown draws no table)
        if not (a + 2 < b and TABLE_SEP_RE.match(self.rec.lines[a + 2])):
            self.rec.lines.insert(a + 2, '|' + '---|' * len(dest_hdr))
            a, b = self.rec.block('archive_body')
            self.act(f'{REC}: restored the separator under the archive table header')
        # non-row lines (split tails etc.) inside the table would be lost on rewrite — skip archiving and have them fixed first
        stray = [(i + 1, l) for i, l in enumerate(self.rec.lines[a + 3:b], a + 3) if l.strip() and not ROW.match(l)]
        if stray:
            self.warn(f'{REC}: non-row lines inside the archive table, so archiving is skipped — fix them first (line: text): '
                      + ' · '.join(f'{n}: `{l.strip()[:40]}`' for n, l in stray[:5]))
        existing = [l for l in self.rec.lines[a + 1:b] if ROW.match(l)]
        moved_by_cls, drop, held = {}, [], []

        for title, s, e in ([] if stray else self.pend.sections()):
            m = re.match(r'^## ([A-Z])\. ', title)
            if not m or m.group(1) not in MOVABLE:
                continue
            cls = m.group(1)
            for i, rid, cs, hdr in table_rows(self.pend.lines, s, e):
                si = col(hdr, 'status')
                if si is None or si >= len(cs) or not is_closed(cs[si]):
                    continue
                if is_orphan_after(self.pend.lines, i):      # the row is split over two lines — moving it would leave the tail in the pending file
                    held.append(rid)
                    self.warn(f'pending {rid}: a non-table line (line {i + 2}) is attached right below the row, so archiving is held — '
                              f'join it to the row or delete it, then run again: `{self.pend.lines[i + 1].strip()[:40]}`')
                    continue
                # map the source table's columns to the §4 schema (ID · item · location · status · note) by key
                out = []
                for name in dest_hdr:
                    j = source_col(hdr, name)
                    out.append(cs[j] if j is not None and j < len(cs) else '')
                ti = col(hdr, 'trigger')
                bi = col(dest_hdr, 'note')
                if ti is not None and ti < len(cs) and cs[ti] and bi is not None:
                    out[bi] = (f'(trigger: {cs[ti]}) ' + out[bi]).strip()
                existing.append('| ' + ' | '.join(out) + ' |')
                moved_by_cls.setdefault(cls, []).append(rid)
                drop.append(i)

        if not drop:
            if not stray and not held:
                self.notes.append('Nothing to archive — no completed or closed items left in the pending file.')
        else:
            for cls, ids in sorted(moved_by_cls.items()):
                self.act(f'{cls} table: completed or closed items archived to completion records §4: {len(ids)} — ' + ' · '.join(ids))
            if self.apply:
                for i in sorted(drop, reverse=True):
                    del self.pend.lines[i]
                a, b = self.rec.block('archive_body')
                self.rec.lines[a + 3:b] = sorted(                 # keep the header and separator; rewrite the rows only
                    existing, key=lambda l: numkey(ROW.match(l).group(1)))

        # update the archive list lines (only categories that have the block)
        a, b = self.rec.block('archive_body')
        now = [ROW.match(l).group(1) for l in self.rec.lines[a:b] if ROW.match(l)]
        for cls in MOVABLE:
            if self.pend.block('archived_list', cls) is None:
                if cls in moved_by_cls:
                    self.warn(f'pending {cls} table has no `<!-- {tok(BLOCKS["archived_list"], cls)} -->` block, so '
                              f'{" · ".join(moved_by_cls[cls])} left no trace of where they were moved. '
                              f'Create the block below the {cls} table and run again.')
                continue
            ids = sorted([i for i in now if i.startswith(cls)], key=numkey)
            if not ids:
                body = [f'> No {cls} items completed or closed have been moved to `{REC_SHOW}` yet.']
            else:
                body = [f'> {len(ids)} completed or closed {cls} items were moved to `{REC_SHOW}` —',
                        '> **' + ' · '.join(ids) + '**.']
            r = self.pend.set_block('archived_list', body, cls)
            if r:
                self.act(f'{cls} archive list line updated (items: {len(ids)})')

    # --- 2) regenerate the record index (records\E*.md → record index) ---
    _idx_mod = None

    def index_module(self):
        """The index rules live in `index_records.py` only; this loads and uses them."""
        if Tidy._idx_mod is None:
            import importlib.util
            p = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'index_records.py')
            if not os.path.exists(p):
                return None
            spec = importlib.util.spec_from_file_location('index_records', p)
            m = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(m)
            Tidy._idx_mod = m
        return Tidy._idx_mod

    def reindex(self):
        m = self.index_module()
        if m is None:
            self.warn(f'{_CFG.tool("index_records.py")} is missing, so the index was not regenerated.')
            return
        text, ents, _ = m.render_index()
        if text is None:
            self.warn(f'{_CFG.records_dir}/E*.md not found. Index regeneration skipped.')
            return
        cur = open(m.IDX, encoding='utf-8').read() if os.path.exists(m.IDX) else ''
        if cur == text:
            self.notes.append(f'{_CFG.record_index_file} up to date — {len(ents)} completion records')
            return
        self.act(f'{_CFG.record_index_file} regenerated ({len(ents)} completion records)')
        if self.apply:
            open(m.IDX, 'w', encoding='utf-8', newline='').write(text)
            self.sync.after_write(_CFG.record_index_file.replace('\\', '/'))

    # --- 3) copy the standing F items from the literature file into the list ---
    def sync_f(self):
        blk = self.hot.block('standing')
        if blk is None:
            self.warn('The list has no `<!-- %s -->` block. Skipping the copy.' % tok(BLOCKS['standing']))
            return
        a, b = blk
        want_ids = [ROW.match(l).group(1) for l in self.hot.lines[a:b] if ROW.match(l)]
        src = {}
        for title, s, e in self.lit.sections():
            if title.startswith('## F.'):
                for i, rid, _, _ in table_rows(self.lit.lines, s, e):
                    src[rid] = self.lit.lines[i]
        miss = [i for i in want_ids if i not in src]
        if miss:
            self.warn(f'Standing F items {miss} are not in `{_CFG.literature_file}` §F.')
            return
        # Keep the two table header lines and replace only what is below them.
        # With an empty block a+2 is the closing line (b), so the slice stops at b —
        # otherwise the closing marker is copied into the body and multiplies on every run.
        head = self.hot.lines[a + 1:min(a + 3, b)]
        body = head + [src[i] for i in want_ids]
        r = self.hot.set_block('standing', body)
        if r:
            self.act(f'Standing environment constraints {want_ids} copied from the literature file')

    # --- 4) checks only ---
    def audit(self):
        # table row format — split rows (orphan lines) · cell count · trailing `|`. The grammar is _config.table_problems only (same as replace_once and the hook)
        for doc, label in [(self.pend, 'pending'), (self.pro, 'proposals'), (self.lit, 'literature'), (self.rec, 'archive')]:
            for prob in table_problems('\n'.join(doc.lines)):
                self.warn(f'{label}: table row format — ' + describe_table_problem(prob))
        # lines that look like rows but were not read as open rows — they reach neither the list nor the sync comparison (S3 · S7) (defined in _unread_rows)
        for label, n, preview in self._unread_rows():
            self.warn(f'{label}: line {n} looks like a row but was not read as an open row — write the ID without decoration (`| A1 |`) inside a category section (`## X.`) '
                      f'or the `| ID |` table of the proposals file: `{preview}`')

        # duplicate and missing IDs
        for doc, label in [(self.rec, 'archive'), (self.pend, 'pending'),
                           (self.lit, 'literature'), (self.pro, 'proposals')]:
            seen = {}
            # the archive file is a single table without `## ` sections — look at the whole file
            spans = [('', 0, len(doc.lines))] if doc is self.rec else doc.sections()
            for title, s, e in spans:
                if title.startswith('## 2.'):      # the renumbering map is not an item table
                    continue
                for i, rid, cs, hdr in table_rows(doc.lines, s, e):
                    if len(cs) < 4:                 # skip index tables (3 columns)
                        continue
                    seen.setdefault(rid, []).append(i + 1)
                for i, rid, _t, _d in entries(doc.lines, s, e):   # items in sub-heading form
                    seen.setdefault(rid, []).append(i + 1)
            dup = {k: v for k, v in seen.items() if len(v) > 1}
            if dup:
                self.warn(f'{label}: duplicate IDs ' + ', '.join(f'{k} (lines {v})' for k, v in dup.items()))

        # completion record files — missing target · missing E numbers (the rules are in index_records.py)
        m = self.index_module()
        if m is not None:
            for w in m.warnings_for(m.read_entries()):
                self.warn(w)

        # H location table ↔ H items
        hids = {r[1] for r in table_rows(self.pro.lines, 0, len(self.pro.lines))
                if r[1].startswith('H')}
        for doc, label in [(self.pro, 'proposals')]:
            bl = doc.block('hand_locations', 'H')
            if bl is None:
                continue
            a, b = bl
            listed = set(re.findall(r'\bH\d+\b', '\n'.join(doc.lines[a:b])))
            if hids - listed:
                self.warn(f'{label} location table is missing proposals: {sorted(hids - listed, key=numkey)}')
            if listed - hids:
                self.warn(f'{label} location table lists proposals that do not exist: {sorted(listed - hids, key=numkey)}')

        # check status and trigger values
        want = {trigger_key(t) for t in TRIGGERS}      # the two spellings of a default trigger count as one trigger
        for title, s, e in self.pend.sections():
            m = re.match(r'^## ([A-Z])\. ', title)
            if not m:
                continue
            for i, rid, cs, hdr in table_rows(self.pend.lines, s, e):
                si = col(hdr, 'status')
                if si is not None and si < len(cs):
                    v = norm(cs[si])
                    if not v:
                        self.warn(f'pending {rid}: empty status value (line {i+1})')
                    elif not state_known(cs[si]):
                        self.warn(f'pending {rid}: unknown status value `{cs[si]}` (line {i+1})')
                ti = col(hdr, 'trigger')
                if ti is None:
                    self.warn(f'pending {cls_of(rid)} table has no `{tok(COLUMNS["trigger"])}` column (line {i+1})')
                elif ti >= len(cs) or not norm(cs[ti]):
                    self.warn(f'pending {rid}: empty trigger value (line {i+1})')
                elif trigger_key(cs[ti]) not in want:
                    self.warn(f'pending {rid}: unknown trigger `{cs[ti]}` (line {i+1}). '
                              f'Allowed values — ' + ' · '.join(TRIGGERS))

    # --- 4.5) regenerate the §3 location table · §4 trigger table · §5 items that can be done now ---
    def _open_spans(self):
        """Where open rows are read — [(document, name, start, end, accepted ID letters)]. Reading rows (_open_rows) and the read checks (_unread_rows · _read_gaps) look at the same places.
        The pending file: the `## X.` sections of the category letters (movable_prefixes); the proposals file: a single table without `## ` sections, so the whole file (H)."""
        out = []
        for title, s, e in self.pend.sections():
            m = re.match(r'^## ([A-Z])[.\s]', title)
            if m and m.group(1) in MOVABLE:
                out.append((self.pend, 'pending', s, e, tuple(MOVABLE)))
        out.append((self.pro, 'proposals', 0, len(self.pro.lines), ('H',)))
        return out

    def _open_rows(self):
        """All open items as (ID, item, location, trigger, status) tuples.

        Looks at A·B·C·D of the pending file together with H of the proposals file (read places: _open_spans).
        H is not archived — a discarded H only gets the status `closed` (see the proposals file header), so completed and closed H are left out.
        H without a status column all count as open. A·B·C·D are not filtered —
        with `--apply`, migrate() moves completed and closed items out first.
        """
        rows = []
        for doc, _label, s, e, only in self._open_spans():
            for i, rid, cs, hdr in table_rows(doc.lines, s, e):
                if not rid.startswith(only):
                    continue
                def cell(j):
                    return cs[j] if j is not None and 0 <= j < len(cs) else ''
                if doc is self.pro and is_closed(cell(col(hdr, 'status'))):
                    continue
                rows.append((rid,
                             strip_md(cell(col_any(hdr, ['item', 'proposal'], 1))),
                             cell(col(hdr, 'location', 2)),
                             strip_md(cell(col(hdr, 'trigger'))),
                             strip_md(cell(col(hdr, 'status')))))
        return rows

    def _unread_rows(self):
        """Lines that look like rows but were not read as open rows — [(name, line number (from 1), preview)].
        `|` lines whose first cell is ID-like (_config.row_like_id) and starts with a letter that file accepts, but which _open_spans did not read as table rows —
        outside the read places (a section that is not a category section) · rows before the `| ID |` header · decorated IDs (`| **A1** |`). Code fences are skipped (as in table_problems)."""
        spans = self._open_spans()
        out = []
        for doc, label, only in [(self.pend, 'pending', tuple(MOVABLE)), (self.pro, 'proposals', ('H',))]:
            read = {r[0] for d, _l, s, e, _o in spans if d is doc for r in table_rows(doc.lines, s, e)}
            in_code = False
            for i, line in enumerate(doc.lines):
                if line.startswith('```'):
                    in_code = not in_code
                    continue
                rid = None if in_code else row_like_id(line)
                if rid and rid.startswith(only) and i not in read:
                    out.append((label, i + 1, line.strip()[:40]))
        return out

    def _read_gaps(self):
        """Reasons the open rows cannot be taken as fully read — [short sentences]. An empty list means the rows read are all there is.

        Decides, when there are zero open items, whether to empty the generated blocks of the list (the table structure of the pending and proposals files is fine
        and there really are zero open rows — the last row was deleted, or everything was archived) or to leave them (rows could not be read — items are not deleted
        because of a read failure). The structure is fine when the pending file has category sections, the pending file's category sections and the proposals file
        have a `| ID |` header, and the read places have neither lines that look like rows but were not read nor table defects (_config.table_problems).
        """
        spans = self._open_spans()
        gaps = []
        if not any(d is self.pend for d, *_ in spans):
            gaps.append('the pending file has no category section (`## X.` — X is %s)' % ' · '.join(MOVABLE))
        for doc, label, where in [(self.pend, 'pending', 'category sections'), (self.pro, 'proposals', 'file')]:
            mine = [(s, e) for d, _l, s, e, _o in spans if d is doc]
            if mine and not any(HDR.match(doc.lines[i]) for s, e in mine for i in range(s, e)):
                gaps.append(f'{label} {where}: no `| ID |` table header')
        unread = self._unread_rows()
        if unread:
            gaps.append('lines that look like rows but were not read — ' + ' · '.join(f'{l} (line {n})' for l, n, _p in unread[:5])
                        + (' …' if len(unread) > 5 else ''))
        bad = [f'{label} (line {s + n})' for doc, label, s, e, _o in spans
               for n, _code, _p in table_problems('\n'.join(doc.lines[s:e]))]
        if bad:
            gaps.append('table row format defects — ' + ' · '.join(bad[:5]) + (' …' if len(bad) > 5 else ''))
        return gaps

    def _rows_or_gaps(self):
        """(open rows, reasons to skip). The reasons matter only when there are zero open items — with reasons, it counts as a read failure and the list stays as it is.
        Table regeneration, focus and generation stamp share this decision (made once, after migrate)."""
        if self._open_state is None:
            rows = self._open_rows()
            self._open_state = (rows, [] if rows else self._read_gaps())
        return self._open_state

    def regen_tables(self):
        rows, gaps = self._rows_or_gaps()
        if gaps:
            self.warn('No open items could be read — the rows cannot be taken as fully read, so the generated blocks of the list (§3–§6) and the generation stamp stay as they are '
                      '(items are not deleted because of a read failure). Fix this and run again: ' + ' · '.join(gaps))
            return
        if not rows:
            self.notes.append('Zero open items — the table structure of the pending and proposals files is fine, so the tables of the list are rebuilt empty.')

        # §3 location table — one row per (file, section). Keys follow the _location.py syntax (same definition as record index §1)
        g = grammar()
        bucket = {}
        for rid, _t, loc, _g, _st in rows:
            keys, p = loc_rows(loc)
            if loc_bad(p):
                self.warn(f'{rid}: cannot parse the location — write the file (path relative to the root, in backticks) and the section: '
                          f'`{strip_md(loc)[:60]}`')
            for k in keys:
                bucket.setdefault(k, []).append(rid)
        C = lambda k: tok(COLUMNS[k])                   # noqa: E731  — written column names
        body = ['| %s | %s | %s |' % (C('file'), C('section'), C('linked')), '|---|---|---|']
        for path, sec, is_file in sorted(bucket, key=loc_sort):
            ids = sorted(set(bucket[(path, sec, is_file)]), key=numkey)
            name = f'`{g.display(path)}`' if is_file else path        # text without a file and blank cells go without backticks (as in record index §1)
            body.append(f'| {name} | {sec or "—"} | ' + ' · '.join(ids) + ' |')
        r = self.hot.set_block('locations', body)
        if r is None:
            self.warn('The list has no `<!-- %s -->` block.' % tok(BLOCKS['locations']))
        elif r:
            self.act(f'§3 location table regenerated (places: {len(bucket)})')

        # §4 trigger table — groups by trigger_key, so the two spellings of a default trigger are one group
        tb, label = {}, {}
        for rid, _t, _l, trig, _st in rows:
            if not trig or is_now(trig):
                continue
            k = trigger_key(trig)
            tb.setdefault(k, []).append(rid)
            label.setdefault(k, next((t for t in TRIGGERS if trigger_key(t) == k), trig))
        order = {trigger_key(t): n for n, t in enumerate(TRIGGERS)}
        body = ['| %s | %s |' % (C('condition'), C('take_up')), '|---|---|']
        for k in sorted(tb, key=lambda x: (order.get(x, 99), x)):
            ids = sorted(set(tb[k]), key=numkey)
            body.append(f'| **{label[k]}** | ' + ' · '.join(ids) + f' ({len(ids)}) |')
        r = self.hot.set_block('triggers', body)
        if r is None:
            self.warn('The list has no `<!-- %s -->` block.' % tok(BLOCKS['triggers']))
        elif r:
            self.act(f'§4 trigger table regenerated (items: {sum(len(v) for v in tb.values())})')

        # §5 items that can be done now
        now = [(rid, t, loc, st) for rid, t, loc, g, st in rows if is_now(g)]
        if not rows:
            body = ['> No open items — the pending and proposals files have no open rows.']
        elif not now:
            body = ['> No item has its trigger cleared. Every open item is waiting for its condition (§4).']
        else:
            body = ['| ID | %s | %s | %s |' % (C('item'), C('location'), C('status')), '|---|---|---|---|']
            for rid, t, loc, st in sorted(now, key=lambda x: numkey(x[0])):
                body.append(f'| **{rid}** | {t} | {loc} | {st} |')
            body.append('')
            body.append(f'> The bodies are in the row with the same ID in `{_CFG.pending_file}`.')
        r = self.hot.set_block('now', body)
        if r is None:
            self.warn('The list has no `<!-- %s -->` block.' % tok(BLOCKS['now']))
        elif r:
            self.act(f'§5 items that can be done now regenerated (items: {len(now)})')

        # whether H is missing from the location table — reads only the ID positions (last cell) (same definition as _config.list_block_ids · sync S3)
        hids = {r0 for r0, *_ in rows if r0.startswith('H')}
        if self.hot.block('locations') and hids:
            listed = {i for i in list_block_ids('\n'.join(self.hot.lines))[0].get('locations', []) if i.startswith('H')}
            if hids - listed:
                self.warn(f'§3 location table is missing proposals: {sorted(hids - listed, key=numkey)}')

    # --- 4.7) §6 chapter in progress ---
    def _focus_target(self):
        """A value given as an argument wins. Otherwise the value written in the §6 block is used as is."""
        if self.focus:
            return None if self.focus in ('off', 'none') else self.focus
        bl = self.hot.block('focus')
        if bl is None:
            return None
        a, b = bl
        m = FOCUS_RE.search('\n'.join(self.hot.lines[a:b]))          # either spelling of the label — the focus survives the migration
        return m.group(1) if m else None

    def regen_focus(self):
        bl = self.hot.block('focus')
        if bl is None:
            if self.focus:
                self.warn('The list has no `<!-- %s -->` block. Create §6 and run again.' % tok(BLOCKS['focus']))
            return
        target = self._focus_target()
        if target is None:
            body = ['> No chapter is set. Turn it on while working on one chapter —',
                    f'> `<py> {_CFG.tool("tidy_tracker.py")} --focus ch3 --apply`',
                    '>   (`<py>` is this computer\'s Python 3 — `python` on Windows, `python3` on macOS)',
                    '>',
                    '> The **bodies** of the open items and proposals tied to that chapter are copied here, so the pending file need not be opened.']
            r = self.hot.set_block('focus', body)
            if r:
                self.act('§6 focus cleared')
            return

        # `ch1` is the file project.json maps to that chapter (e.g. intro.md). An item is included only when the file the location syntax resolved
        # is **equal** to that chapter file — no prefix matching, so note files or a `manuscript/` prefix do not throw it off.
        n = int(target[2:])
        files = [f for c, f in _CFG.chapters if c == n]
        src = _CFG.source_rel
        targets = {(src + '/' + f) if src else f for f in files} | set(files)

        def hits(loc):
            return [(p, s) for p, s, is_file in loc_rows(loc)[0] if is_file and p in targets]

        all_rows, gaps = self._rows_or_gaps()
        if gaps:            # rows not read — keep the copy instead of emptying it (regen_tables gives the warning)
            return
        rows = [r for r in all_rows if hits(r[2])]
        rows.sort(key=lambda r: (min((section_key(s) for _p, s in hits(r[2])), default=(9,)), numkey(r[0])))
        today = datetime.date.today().isoformat()
        body = [f'**{tok(FOCUS_LABEL)}** {target} — set {today} · items: {len(rows)}',
                f'> Turn off: `<py> {_CFG.tool("tidy_tracker.py")} --focus off --apply`',
                '>   (`<py>` is this computer\'s Python 3 — `python` on Windows, `python3` on macOS)',
                '>',
                f'> **Below is a copy of `{_CFG.pending_file}` · `{_CFG.proposals_file}`.** Edit the originals —',
                '> this block is rebuilt by the tidy tool on every run, so edits made here are lost.',
                '']
        for rid, title, loc, trig, st in rows:
            body.append(f'#### {rid} — {title}')
            meta = ' · '.join(x for x in [strip_md(loc), trig, st] if x)
            body.append(f'`{meta}`' if meta else '')
            body.append('')
            body.append(self._note_of(rid))
            body.append('')
        r = self.hot.set_block('focus', body)
        if r:
            self.act(f'§6 focus — {target}: {len(rows)} items included')

    def _note_of(self, rid):
        for doc in (self.pend, self.pro):
            spans = doc.sections() if doc is self.pend else [('', 0, len(doc.lines))]
            for _t, s, e in spans:
                for i, r0, cs, hdr in table_rows(doc.lines, s, e):
                    if r0 != rid:
                        continue
                    j = col_any(hdr, ['note', 'basis'], len(hdr) - 1)
                    return unescape_cell(cs[j]) if j is not None and 0 <= j < len(cs) else ''   # copied into a paragraph, so `\|` → `|`
        return ''

    # --- 5) sizes ---
    def sizes(self):
        print('\nSizes')
        d = os.path.join(self.d, _CFG.records_dir)
        if os.path.isdir(d):
            n = sum(os.path.getsize(os.path.join(d, f)) for f in os.listdir(d)
                    if os.path.isfile(os.path.join(d, f)))
            c = len([f for f in os.listdir(d) if re.fullmatch(r'E\d+\.md', f)])
            label = '%s\\ (%d E files)' % (_CFG.records_dir, c)
            print(f'  {label:24s} {n/1024:7.1f} KB')
        for f in FILES:
            p = os.path.join(self.d, f)
            n = os.path.getsize(p) if os.path.exists(p) else 0
            flag = ''
            if f == _CFG.index_file and n > HOT_LIMIT:      # compare with the settings path, not the name — so the warning fires even when tracker points into a subfolder
                flag = f'  ← over {HOT_LIMIT//1024} KB. This file is read every session; review its structure'
            print(f'  {f:24s} {n/1024:7.1f} KB{flag}')

    # --- 4.8) generation stamp — which sources (pending · proposals · literature) the list was made from. Sync check S4 compares it ---
    def stamp(self):
        if self._rows_or_gaps()[1]:
            # If the generated blocks were not rebuilt because rows could not be read, the stamp stays too — the list was not made from the current sources,
            # and a new stamp would make sync check S4 treat the list as current and hide that it is outdated.
            return
        texts = {}
        for doc, rel in [(self.pend, _CFG.pending_file), (self.pro, _CFG.proposals_file), (self.lit, _CFG.literature_file)]:
            # Hash the bytes that will be on disk after this run — the normalized text save() writes for changed files, the original for unchanged ones.
            # A hand-edited file that differs only in trailing blank lines is not saved, so hashing its normalized text would disagree with sync S4.
            norm = '\n'.join(doc.lines).rstrip() + '\n'
            texts[rel.replace('\\', '/')] = norm if doc.dirty() else doc.orig
        line = self.sync.stamp_for_index(texts)
        prefixes = tuple('<!-- %s ' % w for w in STAMP_WORDS)        # either spelling — an old stamp is replaced, never doubled
        at = [i for i, l in enumerate(self.hot.lines) if l.startswith(prefixes)]
        if not at:
            self.hot.lines.insert(1, line)
            self.act('Generation stamp added to the list')
        elif self.hot.lines[at[0]] != line or len(at) > 1:
            for i in reversed(at[1:]):
                del self.hot.lines[i]
            self.hot.lines[at[0]] = line
            self.act('Generation stamp of the list updated')

    def docs(self):
        """The five files this tool reads and writes — (Doc, name used in the report)."""
        return [(self.hot, _CFG.index_file), (self.pend, _CFG.pending_file), (self.rec, REC),
                (self.lit, _CFG.literature_file), (self.pro, _CFG.proposals_file)]

    def run(self):
        if not refuse_if_alert(self.sync, self.apply, 'tidy_tracker'):
            return 3
        self.migrate()
        self.reindex()
        self.sync_f()
        self.regen_tables()
        self.regen_focus()
        self.stamp()
        self.audit()

        # Pre-save check of the whole set — if there is something to write and any file changed after reading, nothing is saved.
        # All five files are checked, not only the changed ones — if an untouched source changed, the list built from it is outdated.
        if self.apply and any(doc.dirty() for doc, _n in self.docs()):
            self.stale = [name for doc, name in self.docs() if doc.stale()]
            if self.stale:
                return RC_REFUSED

        print('=' * 68)
        print('Tracker tidy — ' + ('applied' if self.apply else 'diagnosis only (--apply to apply)'))
        print('=' * 68)
        if self.acts:
            print('\nTo do' if not self.apply else '\nApplied')
            for a in self.acts:
                print('  ·', a)
        for n in self.notes:
            print('  ·', n)
        if self.warns:
            print('\nNeeds a look — a person has to decide')
            for w in self.warns:
                print('  !', w)
        if not self.acts and not self.warns:
            print('\nAll fine. Nothing to fix or check.')

        changed, blocked = [], []
        for doc, name in self.docs():
            if doc.dirty():
                changed.append(name)
                if self.apply:
                    try:
                        doc.save()
                    except StaleFile:
                        blocked.append(name)
        if blocked:
            print('\n! Not saved — files were changed by someone else after reading: '
                  + ', '.join(blocked))
            print('  They changed between the check and the save. Run again.')
            self.warns.append(f'Concurrent edit detected — {", ".join(blocked)} not overwritten')
            changed = [c for c in changed if c not in blocked]
        if self.apply:
            for name in changed:
                self.sync.after_write(name.replace('\\', '/'))
            findings, removed = self.sync.session_end()       # session end — drive snapshot · retention cleanup
            print('\nSync — session boundary snapshots updated · retention cleanup deleted %d%s' % (removed, ' · ERROR left (needs a look)' if findings else ''))
            for f in findings:
                print('  ! ' + f.line())
        self.sizes()          # measure after saving to get the real sizes
        if changed:
            print(('\nWritten: ' if self.apply else '\nFiles that would change (needs --apply): ') + ', '.join(changed))
        return 1 if self.warns else 0


def main():
    ap = argparse.ArgumentParser(add_help=True)
    ap.add_argument('--apply', action='store_true', help='apply the changes to the files instead of only diagnosing')
    ap.add_argument('--dir', default=project_root())
    ap.add_argument('--focus', metavar='ch3|off',
                    help='when working on one chapter: copies the bodies of the items for that chapter into §6 of the list')
    a = ap.parse_args()
    if a.focus and not re.fullmatch(r'ch\d+|off|none', a.focus):
        print(f'--focus takes ch<chapter number> (the chapters in the settings) or off (got: {a.focus})', file=sys.stderr)
        return 2
    for f in FILES + [REC]:
        if not os.path.exists(os.path.join(a.dir, f)):
            print(f'Missing: {os.path.join(a.dir, f)}', file=sys.stderr)
            return 2
    sync = Sync(_CFG)
    if not a.apply:
        return Tidy(a.dir, False, a.focus, sync).run()
    require_writable_format(_CFG, 'tidy_tracker')          # English anchors only — an old or mixed project is migrated first
    with sync.write_lock('tidy_tracker') as lock:
        if lock.busy:
            print('! ' + lock.busy_message())
            return RC_REFUSED
        stale = []
        for attempt in (1, 2):
            t = Tidy(a.dir, True, a.focus, sync)          # read after taking the lock
            rc = t.run()
            if not t.stale:
                return rc
            stale = t.stale
            if attempt == 1:
                print('Files changed after reading; reading everything again without saving — ' + ', '.join(stale))
        print('! Not saved — files changed after reading in both attempts: ' + ', '.join(stale))
        print('  Another session is writing the same files. Run again.')
        return RC_REFUSED


if __name__ == '__main__':
    sys.exit(main())
