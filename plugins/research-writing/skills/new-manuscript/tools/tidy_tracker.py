r"""Tidy and check the tracker files. File names follow `.manuscript/project.json`; the defaults are shown below.

    tracker_index.md          index · rules · standing constraints. Read in full every session. §3~§5 are generated by this tool
    tracker_pending.md        bodies of the open items A·B·C·D. Get the ID from the index and read only that item
    tracker_records_index.md  record index — generated by tools/index_records.py
    records/E*.md             completion record bodies. One file per item
    records/archive.md        completed items archived from D·B
    tracker_literature.md     literature library F, reference check G
    tracker_proposals.md      proposals H awaiting a decision on adoption

§3 location table · §4 trigger table · §5 items that can be done now — this tool generates all of them from the bodies.

Run it at the end of a session. It moves completed items from the pending file to the completion records
and keeps the index file small enough to read every session.

Usage  (`<py>` is this computer's Python 3 — `python` on Windows, `python3` on macOS)
    <py> tools/tidy_tracker.py                 diagnose only. Changes no file
    <py> tools/tidy_tracker.py --apply         applies what can be fixed
    <py> tools/tidy_tracker.py --dir <path>    folder that holds the files
                                               (default: the parent of the tools folder = the project root)

Where the shell cannot reach the folder (some sync mirrors), run it on staged
copies of the tracker files and copy them back.

Safe to rerun — a second run changes nothing (idempotent).

`--apply` runs "lock → read → compute → check every file for changes since reading → save". It runs even while other sessions are open —
the lock (`_sync.WriteLock`) is held only for this one run, and if any file changed after it was read, **nothing is saved** and everything is read
once more from the start (saving only part would leave a row being archived in neither the pending file nor the archive). The record index
is rebuilt wholesale from the record files, so it is written during the computation.

Format — markers, column names and generated text are written in English; the pre-0.14 Korean spellings are read
(`_config.py` format tokens). `--apply` refuses a project whose anchors are still Korean or mixed (exit 5) — migrate it with
`update_tools.py --apply`.

Exit codes — 0 OK · 1 needs a look (warnings) · 2 argument · missing file · 3 refused by a sync check ERROR ·
            4 save refused (lock not taken, or files changed after reading in both attempts) — run again ·
            5 refused: old-format or mixed anchors.
"""

